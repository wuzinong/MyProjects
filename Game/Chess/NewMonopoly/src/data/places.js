export function citySource(name) {
  const lore = CITY_LORE[name];
  if (!lore) throw Error(`缺少城池介绍：${name}`);
  const volume = lore[1],
    book = volume === 47 ? '三國志' : '後漢書';
  return {
    label: `${volume === 47 ? '三国志·吴主传' : '后汉书·郡国志'}（卷${volume}）`,
    url: `https://zh.wikisource.org/wiki/${book}/卷${volume}`,
  };
}
